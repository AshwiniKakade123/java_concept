public class forloopdemo {
    public static void main(String[] args) {
        
        for(int i = 1 ; i <= 5 ; i++)
        {
            System.out.println(i);
        }

        int arr[]= {10,20,30,40};
        for(int n : arr)
        {
            System.out.println(n);
        }
    }
    
}
